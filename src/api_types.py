class SlotResponse(TypedDict):
    slot_id: int
    """
    An `event_slots` id, the handle a result on this slot names.
    """
    position: int
    """
    Where the slot sits in the schedule, unique within the event.
    """
    lineup_id: int
    """
    A `lineups` id.
    """
    lineup_name: str | None
    """
    The lineup's name. A placeholder lineup, a mode with its tracks unspecified, is named `Placeholder: <mode>`; `tracks` is empty exactly on one, and is what to test rather than the name.
    """
    lineup_short_name: str
    """
    The lineup's short name.
    """
    mode: str
    """
    The mode the lineup belongs to, e.g. `Grand Prix` or `99`. Not the event's own `mode`.
    """
    kind: ModeKind
    max_score: int | None
    """
    The most a score on this slot can be, or null for a mode with no ceiling.
    """
    multiplier: int
    """
    What a result on this slot is worth before anything else is decided.
    """
    starts_at: str | None
    """
    When the slot is raced, as a UTC instant, or null if not entered.
    """
    tracks: list[TrackResponse]
    """
    The lineup's tracks: in race order on a prix slot, the pair put to the vote on a race slot, and empty for a placeholder lineup.
    """
    vote_winner: VoteWinnerResponse | None
    """
    The track voted in on a race slot in the undivided lobby, or null if none is recorded.
    """
    vote_winners: list[LobbyVoteWinnerResponse]
    """
    The track voted in per lobby, one entry for each lobby with a vote recorded. An event with divisions has one lobby per division, and two divisions can hold different winners on one slot.
    """
    lobby: LobbyKind | None
    """
    Null where the slot does not say, which is not public.
    """


class EventDetailResponse(TypedDict):
    scheduled_event_id: int
    """
    An `events_scheduled` id.
    """
    event: str
    """
    The event's name, with no date in it.
    """
    starts_at: str
    """
    When the event opens, as a UTC instant.
    """
    ends_at: str
    """
    When the event closes, as a UTC instant. Exclusive: an event is no longer active at this instant.
    """
    mode: EventMode
    scoring_method: ScoringMethod
    tournament: str | None
    """
    The slug of the tournament this event is part of, the handle `/v1/tournaments/{slug}` takes, or null for a weekly or any event outside one.
    """
    group_kind: GroupKind | None
    """
    Null for an event with neither divisions nor teams.
    """
    groups: list[EventGroupResponse]
    """
    The event's divisions or teams, as `group_kind` says, in display order. Empty when null.
    """
    slots: list[SlotResponse]
    """
    The schedule, in position order; the same list `/schedule` answers.
    """
    scoring: ScoringConfigResponse
